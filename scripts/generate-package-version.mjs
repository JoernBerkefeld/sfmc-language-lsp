// Embed package metadata before every supported build entry; runtime stays browser-safe.
import { readFileSync, writeFileSync } from 'node:fs';

const { version } = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
writeFileSync(
    new URL('../src/package-version.ts', import.meta.url),
    `// Generated by scripts/generate-package-version.mjs; do not edit.\nexport const LSP_PACKAGE_VERSION: string = '${version}';\n`,
);
